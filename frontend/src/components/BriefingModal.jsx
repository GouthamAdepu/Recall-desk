import { useEffect, useState } from "react";
import { FileText, Copy, Check, Loader2 } from "lucide-react";
import Modal from "./Modal.jsx";
import { api } from "../api.js";

const HEADERS = [
  "CUSTOMER SNAPSHOT",
  "ISSUE TIMELINE",
  "ALREADY TRIED (DO NOT REPEAT)",
  "OPEN PROMISES",
  "CUSTOMER SENTIMENT",
  "RECOMMENDED NEXT ACTION",
];

// Split the Reflect output into sections for nicer rendering (falls back to raw text).
function sections(text) {
  const out = [];
  let current = null;
  for (const line of text.split("\n")) {
    const clean = line.replace(/[#*:]/g, "").trim().toUpperCase();
    const header = HEADERS.find((h) => clean === h || clean.startsWith(h));
    if (header) {
      current = { title: header, lines: [] };
      out.push(current);
    } else if (line.trim()) {
      if (!current) {
        current = { title: "", lines: [] };
        out.push(current);
      }
      current.lines.push(line.replace(/^\s*[-•*]\s*/, "").trim());
    }
  }
  return out;
}

export default function BriefingModal({ customer, onClose }) {
  const [text, setText] = useState("");
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    api
      .briefing(customer.id)
      .then((r) => (r.memory_available ? setText(r.briefing) : setError("Hindsight is unreachable.")))
      .catch((e) => setError(e.message))
      .finally(() => setLoading(false));
  }, [customer.id]);

  const copy = async () => {
    await navigator.clipboard.writeText(`Handoff: ${customer.name} (${customer.id})\n\n${text}`);
    setCopied(true);
    setTimeout(() => setCopied(false), 1500);
  };

  return (
    <Modal
      icon={FileText}
      title={`Tier-2 handoff: ${customer.name}`}
      subtitle="Generated by Hindsight Reflect from this customer's memory bank. No transcript reading needed."
      onClose={onClose}
    >
      {loading ? (
        <div className="flex items-center gap-2 py-10 text-sm text-slate-400">
          <Loader2 className="h-4 w-4 animate-spin" /> Hindsight is reflecting on the full history…
        </div>
      ) : error ? (
        <p className="text-sm text-amber-300">⚠️ {error}</p>
      ) : (
        <>
          <div className="space-y-3">
            {sections(text).map((s, i) => (
              <div key={i} className="rounded-xl border border-white/5 bg-slate-950/50 p-3">
                {s.title && (
                  <div className="mb-1.5 text-[11px] font-bold uppercase tracking-wider text-indigo-300">{s.title}</div>
                )}
                <ul className="space-y-1">
                  {s.lines.map((l, j) => (
                    <li key={j} className="text-[13px] leading-snug text-slate-200">• {l}</li>
                  ))}
                </ul>
              </div>
            ))}
          </div>
          <div className="mt-4 flex justify-end">
            <button className="btn-ghost" onClick={copy}>
              {copied ? <Check className="h-4 w-4 text-emerald-400" /> : <Copy className="h-4 w-4" />}
              {copied ? "Copied" : "Copy for ticket"}
            </button>
          </div>
        </>
      )}
    </Modal>
  );
}
